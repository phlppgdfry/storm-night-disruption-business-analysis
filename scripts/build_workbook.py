#!/usr/bin/env python3
"""Build data/storm-night-business-case.xlsx from the model and the generated results.

Sheets: README · Assumptions · Simulation (medians) · Business case (live formulas on the assumptions) · Policies · Tornado.
The business-case sheet recalculates in Excel when an assumption is changed; the simulated per-event figures are inputs
from scripts/build-results.mjs (Excel cannot run the simulation).
Run: python3 scripts/build_workbook.py   (needs openpyxl)
"""
from __future__ import annotations

import json
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

ROOT = Path(__file__).resolve().parent.parent
A = json.loads((ROOT / "model/assumptions.json").read_text())["assumptions"]
R = json.loads((ROOT / "site/data/results.json").read_text())

HEAD = Font(bold=True, color="FFFFFF")
FILL = PatternFill("solid", fgColor="24508F")
INPUT = PatternFill("solid", fgColor="FFF4CC")


def header(ws, row, values):
    for i, v in enumerate(values, 1):
        c = ws.cell(row=row, column=i, value=v)
        c.font, c.fill = HEAD, FILL


def widths(ws, ws_widths):
    for i, w in enumerate(ws_widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


wb = Workbook()
ws = wb.active
ws.title = "README"
for i, line in enumerate([
    "Storm Night — business case workbook",
    "Fictional operator (Tidewell Shortsea Lines). Illustrative assumptions — not real company data.",
    "Generated by scripts/build_workbook.py from model/assumptions.json and site/data/results.json.",
    "Yellow cells on 'Assumptions' are inputs: change one and 'Business case' recalculates.",
    "Per-event savings come from 200 simulated storm nights (AS-IS vs TO-BE on the same freight); Excel cannot run the simulation itself.",
], 1):
    ws.cell(row=i, column=1, value=line).font = Font(bold=(i == 1), size=14 if i == 1 else 11)
widths(ws, [120])

# Assumptions
wa = wb.create_sheet("Assumptions")
header(wa, 1, ["ID", "Key", "Assumption", "Base", "Low", "High", "Unit", "Group", "Why"])
row_of = {}
for r, a in enumerate(A, 2):
    for c, v in enumerate([a["id"], a["key"], a["label"], a["value"], a["low"], a["high"], a["unit"], a["group"], a["why"]], 1):
        wa.cell(row=r, column=c, value=v)
    wa.cell(row=r, column=4).fill = INPUT
    row_of[a["key"]] = r
widths(wa, [7, 22, 70, 10, 10, 10, 12, 16, 80])
ref = lambda key: f"Assumptions!$D${row_of[key]}"  # noqa: E731

# Simulation medians
wsim = wb.create_sheet("Simulation")
header(wsim, 1, ["KPI", "AS-IS P10", "AS-IS P50", "AS-IS P90", "TO-BE P10", "TO-BE P50", "TO-BE P90"])
for r, (key, label) in enumerate(R["kpiLabels"].items(), 2):
    vals = [R["asis"][key][q] for q in ("p10", "p50", "p90")] + [R["tobe"][key][q] for q in ("p10", "p50", "p90")]
    wsim.cell(row=r, column=1, value=label)
    for c, v in enumerate(vals, 2):
        wsim.cell(row=r, column=c, value=v)
widths(wsim, [70, 11, 11, 11, 11, 11, 11])

# Business case with live formulas
wb_ = wb.create_sheet("Business case")
bc = R["businessCase"]
rows = [
    ("Median saving per event: perishables (at base goodwill)", bc["byLine"]["perishables"], "input from simulation"),
    ("Median saving per event: withdrawn units (at base margin)", bc["byLine"]["withdrawn"], "input from simulation"),
    ("Median saving per event: call handling", bc["byLine"]["calls"], "input from simulation"),
    ("Perishable saving rescaled to goodwill in Assumptions", f"=B2/2500*{ref('perishableLateCost')}", "formula"),
    ("Withdrawn saving rescaled to margin in Assumptions", f"=B3/420*{ref('marginPerUnit')}", "formula"),
    ("Saving per event", "=B5+B6+B4", "formula"),
    ("Events per year", f"={ref('eventsPerYear')}", "A-40"),
    ("Saving per year", "=B7*B8", "formula"),
    ("Run cost per year", f"={ref('runCost')}", "A-42"),
    ("Net benefit per year", "=B9-B10", "formula"),
    ("Build cost", f"={ref('buildCost')}", "A-41"),
    ("Discount rate", f"={ref('discountRate')}", "A-43"),
    ("Years", f"={ref('years')}", "A-44"),
    ("NPV", "=-B12+B11*(1-(1+B13)^(-B14))/B13", "formula"),
    ("Payback (months)", "=IF(B11>0,B12/B11*12,\"never\")", "formula"),
    ("Simulated NPV P10 / P50 / P90 (200 nights)", f"{bc['npv']['p10']} / {bc['npv']['p50']} / {bc['npv']['p90']}", "from build-results"),
    ("Chance of negative NPV, all assumptions uncertain", R["uncertainty"]["probabilityNegative"], "from build-results"),
]
header(wb_, 1, ["Line", "Value", "Source"])
for r, (label, value, source) in enumerate(rows, 2):
    wb_.cell(row=r, column=1, value=label)
    wb_.cell(row=r, column=2, value=value)
    wb_.cell(row=r, column=3, value=source)
    wb_.cell(row=r, column=2).number_format = "#,##0"
wb_["B13"].number_format = "0%"
wb_["B18"].number_format = "0.0%"
widths(wb_, [58, 22, 22])

# Policies
wp = wb.create_sheet("Policies")
keys = ["perishablesLate", "delayContractH", "delayOtherH", "driverHours", "emptyLmWhileWaiting"]
header(wp, 1, ["Policy"] + [R["kpiLabels"][k] for k in keys])
for r, (pid, label) in enumerate([("asis", "AS-IS (phones)"), ("fifo", "First booked, first rebooked"), ("keyAccountsFirst", "Key accounts first"), ("perishablesFirst", "Perishables and drivers first"), ("recommended", "Recommended (D-04)")], 2):
    src = R["asis"] if pid == "asis" else R["policies"][pid]
    wp.cell(row=r, column=1, value=label)
    for c, k in enumerate(keys, 2):
        wp.cell(row=r, column=c, value=src[k]["p50"])
widths(wp, [34] + [24] * len(keys))
for c in range(2, len(keys) + 2):
    wp.cell(row=1, column=c).alignment = Alignment(wrap_text=True)

# Tornado
wt = wb.create_sheet("Tornado")
header(wt, 1, ["ID", "Assumption", "Low", "NPV at low", "High", "NPV at high", "Swing"])
for r, b in enumerate(R["tornado"]["bars"], 2):
    for c, v in enumerate([b["id"], b["label"], b["low"], b["npvLow"], b["high"], b["npvHigh"], b["swing"]], 1):
        wt.cell(row=r, column=c, value=v)
widths(wt, [7, 70, 10, 14, 10, 14, 14])

out = ROOT / "data/storm-night-business-case.xlsx"
out.parent.mkdir(exist_ok=True)
wb.save(out)
print(f"wrote {out.relative_to(ROOT)}")
